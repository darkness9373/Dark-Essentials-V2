"""Generate per-version raw_id tables under scripts/data/aux_tables/ + index scripts/data/item_aux.js.

Usage (PowerShell):
    $vers = @("1.26.50.4", "1.26.60.29-preview")
    foreach ($v in $vers) {
        Invoke-WebRequest -Uri "https://raw.githubusercontent.com/Mojang/bedrock-samples/v$v/metadata/vanilladata_modules/mojang-items.json" -OutFile "aux-items-$v.json"
        Invoke-WebRequest -Uri "https://raw.githubusercontent.com/Mojang/bedrock-samples/v$v/metadata/vanilladata_modules/mojang-blocks.json" -OutFile "aux-blocks-$v.json"
    }
    python tools/gen_aux.py 1.26.50.4 1.26.60.29-preview

Reads aux-items-<ver>.json + aux-blocks-<ver>.json from CWD, writes
scripts/data/aux_tables/aux_<sanitized-ver>.js (raw_id per string id,
one file per version) plus the scripts/data/item_aux.js index.
aux is computed at lookup time: signed32((raw_id << 16) | (data & 0xffff)).
Glint folds into aux as +32768 on the data bits (verified against DSUI BP
forms.js/chest.js: `(ID ...) * 65536 + (enchanted ? 32768 : 0)`).
"""

import json
import sys
from pathlib import Path

CWD = Path.cwd()
DATA_DIR = Path(__file__).resolve().parent.parent / "scripts" / "data"
AUX_DIR = DATA_DIR / "aux_tables"
DST = DATA_DIR / "item_aux.js"


def load_table(ver):
    items = json.loads((CWD / f"aux-items-{ver}.json").read_text())["data_items"]
    blocks = json.loads((CWD / f"aux-blocks-{ver}.json").read_text())["data_items"]
    merged = {}
    for x in items:
        raw, name = x.get("raw_id"), x.get("name") or x.get("command_name")
        if isinstance(raw, int) and name:
            merged[name] = raw
    for x in blocks:
        raw, name = x.get("raw_id"), x.get("name")
        if isinstance(raw, int) and name and name not in merged:
            merged[name] = raw
    return dict(sorted(merged.items()))


def ident(ver):
    return "AUX_" + "".join(c if c.isalnum() else "_" for c in ver)


def main(vers):
    tables = {ver: load_table(ver) for ver in vers}
    AUX_DIR.mkdir(parents=True, exist_ok=True)
    wanted = set()
    for ver in vers:
        fname = "aux_" + ident(ver)[4:].lower() + ".js"
        wanted.add(fname)
        lines = [
            "// Generated by tools/gen_aux.py from Mojang bedrock-samples metadata",
            "// (vanilladata_modules/mojang-items.json + mojang-blocks.json).",
            f"// Game version: {ver}. Stores raw_id per string id; aux is derived at lookup.",
            "export const VERSION = " + json.dumps(ver) + ";",
            "export const RAW = " + json.dumps(tables[ver], separators=(",", ":")) + ";",
        ]
        (AUX_DIR / fname).write_text("\n".join(lines) + "\n")
    for stale in AUX_DIR.glob("aux_*.js"):
        if stale.name not in wanted:
            stale.unlink()
    lines = [
        "// Generated by tools/gen_aux.py. Per-version raw_id tables live in ./aux_tables/.",
        "// Re-run the generator to add a version; it rewrites this index.",
        "// aux = signed32((raw_id << 16) | (data & 0xffff)).",
        "// Glint folds into aux as +32768 on the data bits (DSUI BP pattern).",
        "// e.g. iconOf('minecraft:diamond_sword', { glint: true }) -> aux + 32768.",
    ]
    for ver in vers:
        fname = "aux_" + ident(ver)[4:].lower() + ".js"
        lines.append(f"import {{ RAW as {ident(ver)} }} from \"./aux_tables/{fname}\";")
    lines.append("/**")
    lines.append(" * Daftar versi game yang punya tabel raw_id, urut dari lama ke baru.")
    lines.append(" * Versi terakhir dipakai sebagai fallback bila version tidak dikenal.")
    lines.append(" * @example AUX_VERSIONS[0]; // \"1.26.50.4\"")
    lines.append(" */")
    lines.append("export const AUX_VERSIONS = " + json.dumps(vers) + ";")
    lines.append("const TABLES = {")
    for ver in vers:
        lines.append("    " + json.dumps(ver) + ": " + ident(ver) + ",")
    lines.append("};")
    lines.append("function tableOf(version) {")
    lines.append("    return TABLES[version] ?? TABLES[AUX_VERSIONS[AUX_VERSIONS.length - 1]];")
    lines.append("}")
    lines.append("/**")
    lines.append(" * Ambil raw_id numerik Mojang untuk sebuah string id item/block.")
    lines.append(" * @param {string} id String id, misal \"minecraft:chest\" (case-insensitive).")
    lines.append(" * @param {string} [version] Versi game dari AUX_VERSIONS; fallback versi terbaru bila kosong/tak dikenal.")
    lines.append(" * @returns {number | null} raw_id, atau null bila id tidak ada di tabel.")
    lines.append(" * @example rawOf(\"minecraft:chest\", \"1.26.50.4\"); // 54")
    lines.append(" */")
    lines.append("export function rawOf(id, version) {")
    lines.append("    const v = tableOf(version)[String(id ?? '').trim().toLowerCase()];")
    lines.append("    return typeof v === 'number' ? v : null;")
    lines.append("}")
    lines.append("/**")
    lines.append(" * Hitung aux_id renderer (signed 32-bit) dari raw_id: (raw_id << 16) | data.")
    lines.append(" * Glint/enchant shine dilipat ke bit data sebagai +32768 (pola DSUI BP).")
    lines.append(" * @param {string} id String id, misal \"minecraft:chest\".")
    lines.append(" * @param {string} [version] Versi game; fallback versi terbaru.")
    lines.append(" * @param {number} [data=0] Nilai data/varian (0-65535).")
    lines.append(" * @param {boolean} [glint=false] True tambah efek glint (+32768).")
    lines.append(" * @returns {number | null} aux_id signed 32-bit, atau null bila id tak dikenal.")
    lines.append(" * @example auxOf(\"minecraft:chest\", \"1.26.50.4\"); // 3538944")
    lines.append(" */")
    lines.append("export function auxOf(id, version, data = 0, glint = false) {")
    lines.append("    const raw = rawOf(id, version);")
    lines.append("    if (raw === null) return null;")
    lines.append("    const d = (Math.floor(Number(data) || 0) & 0xffff) | (glint ? 32768 : 0);")
    lines.append("    return (raw << 16) | d;")
    lines.append("}")
    lines.append("/**")
    lines.append(" * Bentuk ringkas aux_id ikon untuk binding renderer (#item_id_aux).")
    lines.append(" * @param {string} id String id item/block.")
    lines.append(" * @param {object} [options] Opsi ikon.")
    lines.append(" * @param {string} [options.version] Versi game; fallback versi terbaru.")
    lines.append(" * @param {number} [options.data=0] Nilai data/varian.")
    lines.append(" * @param {boolean} [options.glint=false] True tambah efek glint.")
    lines.append(" * @returns {number | null} aux_id, atau null bila id tak dikenal.")
    lines.append(" * @example iconOf(\"minecraft:diamond_sword\", { glint: true });")
    lines.append(" */")
    lines.append("export function iconOf(id, options = {}) {")
    lines.append("    const o = options !== null && typeof options === 'object' ? options : {};")
    lines.append("    return auxOf(id, o.version, o.data ?? 0, o.glint ?? false);")
    lines.append("}")
    DST.write_text("\n".join(lines) + "\n")
    print("written", DST, {v: len(t) for v, t in tables.items()})


if __name__ == "__main__":
    main(sys.argv[1:])
